package com.taskmanager.backend.model;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

public class Task {

    private Long id;
    

    // Title must contain non-whitespace text and fit the database column
    @NotBlank(message = "Task title is required")
    @Size(max = 150, message = "Title cannot exceed 150 characters")
    private String title;

    // Description is optional, but cannot exceed 500 characters
    @Size(max = 500, message = "Description cannot exceed 500 characters")
    private String description;

    // Requires a status that matches one of our defined enum constants
    @NotNull(message = "Task status is required")
    private TaskStatus status;

    // Requires a priority that matches one of our defined enum constants
    @NotNull(message = "Task priority is required")
    private TaskPriority priority;

    // No-argument constructor used when Spring converts JSON into a Task
    public Task() {
    }

    // Constructor used when creating Task objects from database rows
    public Task(Long id, String title, String description,
                TaskStatus status, TaskPriority priority, Long userId) {
        this.id = id;
        this.title = title;
        this.description = description;
        this.status = status;
        this.priority = priority;
        this.userId = userId;
    }

    // Returns the enum representing the task's status
    public TaskStatus getStatus() {
        return status;
    }

    // Returns the enum representing the task's priority
    public TaskPriority getPriority() {
        return priority;
    }

    // Sets the task's status using a valid enum constant
    public void setStatus(TaskStatus status) {
        this.status = status;
    }

    // Sets the task's priority using a valid enum constant
    public void setPriority(TaskPriority priority) {
        this.priority = priority;
    }

    // Returns the task's database ID -----------
    public Long getId() {
        return id;
    }

    // Sets the ID generated by MySQL after inserting a task
    public void setId(Long id) {
        this.id = id;
    }

    // Returns the task title
    public String getTitle() {
        return title;
    }

    // Returns the task description
    public String getDescription() {
        return description;
    }

    // Updates the task title
    public void setTitle(String title) {
        this.title = title;
    }

    // Updates the task description
    public void setDescription(String description) {
        this.description = description;
    }

    // Add this field to the existing Task class
    private Long userId;

    // Add these methods to expose the owner ID
    public Long getUserId() {
        return userId;
    }

    public void setUserId(Long userId) {
        this.userId = userId;
    }
}
