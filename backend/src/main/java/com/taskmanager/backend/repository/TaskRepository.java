package com.taskmanager.backend.repository;

import java.sql.PreparedStatement;
import java.sql.Statement;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;

import com.taskmanager.backend.model.Task;
import com.taskmanager.backend.model.TaskPriority;
import com.taskmanager.backend.model.TaskStatus;


// Marks this class as the database-access layer.
@Repository
public class TaskRepository {

    // Spring injects JdbcTemplate, which uses the configured DataSource
    // and HikariCP connection pool to manage database connections.
    private final JdbcTemplate jdbcTemplate;

    // Constructor injection gives this repository its JdbcTemplate.
    public TaskRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    // Converts each SQL result row into a Java Task object.
    // This mapping is reused by findAll() and findById().
   // UPDATED: Now reads due_date from MySQL and passes it to the Task constructor
    private final RowMapper<Task> taskRowMapper = (result, rowNum) -> {
        java.sql.Date sqlDate = result.getDate("due_date");
        java.time.LocalDate dueDate = (sqlDate != null) ? sqlDate.toLocalDate() : null;
        
        return new Task(
            result.getLong("id"),
            result.getString("title"),
            result.getString("description"),
            TaskStatus.valueOf(result.getString("status")),
            TaskPriority.valueOf(result.getString("priority")),
            result.getLong("user_id"),
            dueDate // New 7th parameter!
        );
    };

    // Retrieves every task from the database.
    public List<Task> findAll() {
        String sql = "SELECT * FROM tasks";

        // JdbcTemplate executes the SQL and maps each row into a Task.
        return jdbcTemplate.query(sql, taskRowMapper);
    }

    // Retrieves one task by ID, or returns null if it does not exist.
    public Task findById(Long id) {
        String sql = "SELECT * FROM tasks WHERE id = ?";

        // The ? placeholder is safely populated with the supplied ID.
        List<Task> tasks = jdbcTemplate.query(sql, taskRowMapper, id);

        // Avoids an exception when the query returns no rows.
        return tasks.isEmpty() ? null : tasks.get(0);
    }

    // Inserts a new task and retrieves its generated database ID.
    public Task save(Task task) {
        String sql =
            "INSERT INTO tasks (title, description, status, priority, user_id, due_date) " +
            "VALUES (?, ?, ?, ?, ?, ?)";

             // Keep track of the automatically generated task ID.
            org.springframework.jdbc.support.GeneratedKeyHolder keyHolder =
            new org.springframework.jdbc.support.GeneratedKeyHolder();


        // KeyHolder captures the ID generated by MySQL.
        //KeyHolder keyHolder = new GeneratedKeyHolder();

        // JdbcTemplate prepares and executes the insert statement.
        jdbcTemplate.update(connection -> {
            // Ask MySQL to return the generated primary key.
            PreparedStatement statement = connection.prepareStatement(
                sql, Statement.RETURN_GENERATED_KEYS
            );

            // Bind values to placeholders rather than concatenating SQL.
            statement.setString(1, task.getTitle());
            statement.setString(2, task.getDescription());
            statement.setString(3, task.getStatus().name());
            statement.setString(4, task.getPriority().name());
            statement.setLong(5, task.getUserId()); // Set the ID of the user who owns this task.
        
            // Safely handle null dates
            if (task.getDueDate() != null) {
                statement.setDate(6, java.sql.Date.valueOf(task.getDueDate()));
            } else {
                statement.setNull(6, Types.DATE);
            }
            return statement;
        }, keyHolder);

        // Put the generated database ID back into the Java object.
        Number generatedId = keyHolder.getKey();

        if (generatedId == null) {
            // Fail clearly if the database did not return an ID.
            throw new IllegalStateException(
                "Task was inserted, but MySQL did not return its generated ID."
            );
        }

        task.setId(generatedId.longValue());

        return task;
    }

    // Updates an existing task and reports whether a row was changed.
    // UPDATED: Completely safe SQL update explicitly defining data types
    public boolean update(Task task) {
        String sql =
            "UPDATE tasks SET title = ?, description = ?, " +
            "status = ?, priority = ?, due_date = ? WHERE id = ?";

        int rowsUpdated = jdbcTemplate.update(
            sql,
            new Object[]{
                task.getTitle(),
                task.getDescription(),
                task.getStatus().name(),
                task.getPriority().name(),
                task.getDueDate() != null ? java.sql.Date.valueOf(task.getDueDate()) : null,
                task.getId()
            },
            new int[]{
                Types.VARCHAR,
                Types.VARCHAR,
                Types.VARCHAR,
                Types.VARCHAR,
                Types.DATE,       // Explicitly tells MySQL this is a date, even if null!
                Types.BIGINT
            }
        );
        return rowsUpdated > 0;
    }

    // Deletes a task by ID and reports whether a row was deleted.
    public boolean deleteById(Long id) {
        String sql = "DELETE FROM tasks WHERE id = ?";

        // Returns true when the database reports a deleted row.
        int rowsDeleted = jdbcTemplate.update(sql, id);

        return rowsDeleted > 0;
    }

    // Retrieves a filtered, sorted page of tasks.
    public List<Task> findTasks(
            String status,
            String priority,
            String sortBy,
            String direction,
            int page,
            int size) {

        // Start with a query that can be extended by optional filters.
        StringBuilder sql = new StringBuilder("SELECT * FROM tasks WHERE 1=1");

        // Store filter values separately so they are safely parameterized.
        List<Object> params = new ArrayList<>();

        // Add the status filter only when the client supplied one.
        if (status != null && !status.isBlank()) {
            sql.append(" AND status = ?");
            params.add(status);
        }

        // Add the priority filter only when the client supplied one.
        if (priority != null && !priority.isBlank()) {
            sql.append(" AND priority = ?");
            params.add(priority);
        }

        // Allow only known database columns in the ORDER BY clause.
        // SQL identifiers cannot be safely supplied as ordinary ? parameters.
        String sortColumn = switch (sortBy == null ? "id" : sortBy) {
            case "title" -> "title";
            case "status" -> "status";
            case "priority" -> "priority";
            case "dueDate" -> "due_date";
            case "id" -> "id";
            default -> throw new IllegalArgumentException("Unsupported sort field");
        };

        // Allow only ASC or DESC to prevent SQL injection through direction.
        String sortDirection = "desc".equalsIgnoreCase(direction) ? "DESC" : "ASC";

        // Add a stable secondary sort so rows with equal values have an order.
        sql.append(" ORDER BY ").append(sortColumn)
        .append(" ").append(sortDirection);

        // Calculate how many rows to skip before the requested page.
        int offset = page * size;

        // Add pagination directly to the SQL query.
        sql.append(" LIMIT ? OFFSET ?");
        params.add(size);
        params.add(offset);

        // Execute the query and map every result row into a Task.
        return jdbcTemplate.query(sql.toString(), taskRowMapper, params.toArray());
    }

    // Counts how many tasks match the supplied filters.
    public long countTasks(String status, String priority) {

        // Build the count query using the same filters as the page query.
        StringBuilder sql = new StringBuilder(
            "SELECT COUNT(*) FROM tasks WHERE 1=1"
        );

        // Keep filter values separate from the SQL string.
        List<Object> params = new ArrayList<>();

        // Apply the optional status filter.
        if (status != null && !status.isBlank()) {
            sql.append(" AND status = ?");
            params.add(status);
        }

        // Apply the optional priority filter.
        if (priority != null && !priority.isBlank()) {
            sql.append(" AND priority = ?");
            params.add(priority);
        }

        // Return the total number of matching rows, not just this page.
        Long count = jdbcTemplate.queryForObject(
            sql.toString(), Long.class, params.toArray()
        );

        return count == null ? 0L : count;
    }

    // Retrieve all tasks owned by a specific user.
    public List<Task> findByUserId(Long userId) {

        // The parameterized query prevents SQL injection.
        String sql = "SELECT * FROM tasks WHERE user_id = ? ORDER BY id";

        // Convert the matching database rows into Task objects.
        return jdbcTemplate.query(sql, taskRowMapper, userId);
    }

}