package com.taskmanager.backend.repository;

import java.util.List;
import java.util.Optional;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;

import com.taskmanager.backend.model.User;

@Repository
public class UserRepository {

    private final JdbcTemplate jdbcTemplate;

    // Spring injects the configured JdbcTemplate
    public UserRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    // Convert each database row into a User object
    private final RowMapper<User> userRowMapper = (result, rowNum) ->
        new User(
            result.getLong("id"),
            result.getString("name"),
            result.getString("email")
        );

    // Save a new user and return the generated ID
    public Long save(User user) {
        String sql = "INSERT INTO users (name, email) VALUES (?, ?)";

        // Store the generated ID in a holder
        org.springframework.jdbc.support.GeneratedKeyHolder keyHolder =
            new org.springframework.jdbc.support.GeneratedKeyHolder();

        jdbcTemplate.update(connection -> {
            // Request the auto-generated primary key
            java.sql.PreparedStatement statement =
                connection.prepareStatement(
                    sql,
                    java.sql.Statement.RETURN_GENERATED_KEYS
                );

            // Bind user values safely
            statement.setString(1, user.getName());
            statement.setString(2, user.getEmail());

            return statement;
        }, keyHolder);

        // Return the ID generated by MySQL
        Number key = keyHolder.getKey();

        if (key == null) {
            throw new IllegalStateException("User ID was not generated");
        }

        return key.longValue();
    }

    // Find a user by ID; Optional.empty() means it does not exist
    public Optional<User> findById(Long id) {
        String sql = "SELECT * FROM users WHERE id = ?";

        List<User> users = jdbcTemplate.query(
            sql,
            userRowMapper,
            id
        );

        return users.stream().findFirst();
    }

    // Retrieve all users
    public List<User> findAll() {
        String sql = "SELECT * FROM users ORDER BY id";

        return jdbcTemplate.query(sql, userRowMapper);
    }

    // Find a user by their unique email address.
    public Optional<User> findByEmail(String email) {
        // Parameterized SQL keeps the query safe from SQL injection.
        String sql = "SELECT * FROM users WHERE email = ?";

        // Return the matching user, or an empty Optional if none exists.
        List<User> users = jdbcTemplate.query(sql, userRowMapper, email);

        return users.stream().findFirst();
    }
}